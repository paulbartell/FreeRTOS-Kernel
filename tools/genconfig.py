import kconfiglib
import argparse
import os

def main():
    arg_parser = argparse.ArgumentParser(description='')
    arg_parser.add_argument(
        "-i",
        "--in-file",
        help="input config file",
    )

    arg_parser.add_argument(
        "-o",
        "--out-file",
        help="output file path",
    )

    args = arg_parser.parse_args()

    config = kconfiglib.Kconfig()

    config.load_config( args.in_file )

    config_header_line = "/* This FreeRTOSConfig.h has been auto-generated by genconfig.py. Do not edit manually. */"

    config_header_lines = [config_header_line]
    for symbol in config.unique_defined_syms:
        # Only Output FreeRTOS config items
        if symbol.config_string and len(symbol.str_value) > 0:
            if symbol.name.startswith('config') or symbol.name.startswith('INCLUDE'):
                # print("Symbol: {}, Value: \"{}\"".format(symbol.name, symbol.str_value));
                if symbol.orig_type == kconfiglib.BOOL:
                    if symbol.str_value == 'y':
                        config_header_lines.append('#define {} 1'.format(symbol.name))
                    else:
                        config_header_lines.append('#define {} 0'.format(symbol.name))
                elif symbol.orig_type in kconfiglib._INT_HEX:
                    value = 0
                    if symbol.orig_type == kconfiglib.HEX:
                        value = int(symbol.str_value, 16)
                    elif  symbol.orig_type == kconfiglib.INT:
                        value = int(symbol.str_value, 10)
                    config_header_lines.append('#define {} 0x{:02x}'.format(symbol.name, value))
                elif symbol.orig_type == kconfiglib.STRING:
                    # Escape the string
                    cfg_value = kconfiglib.escape(symbol.str_value)
                    if symbol.name.endswith('_TYPE'):
                        config_header_lines.append('#define {} {}'.format(symbol.name, cfg_value))
                    else:
                        config_header_lines.append('#define {} \"{}\"'.format(symbol.name, cfg_value))

    config_header_lines.append("")

    config_header_contents = '\n'.join(config_header_lines)

    if(os.path.exists(args.out_file)):
        config._write_if_changed( args.out_file, config_header_contents )
    else:
        with open(args.out_file, 'w', encoding="utf-8") as f:
            f.write(config_header_contents)

if __name__ == "__main__":
    main()